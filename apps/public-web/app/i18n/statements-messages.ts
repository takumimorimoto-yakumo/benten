/**
 * Copy of the financial statements (the company page section and the
 * evidence page's annual history) for every supported locale. Registered
 * for non-Latin text in catalog-manifest.json.
 *
 * Line and statement names are the standard accounting names of each
 * language (Gross profit, Return on equity (ROE), the Korean name of the
 * income statement), because investors read them as those terms. They are
 * rendered only inside `data-term="accounting-line-item"` elements
 * (`AccountingTerm`), the one place the vocabulary rule (app IA section 7)
 * lets a standard accounting name carry a word it otherwise keeps off the
 * page. Every other string follows the rule: no text ranks, rates, forecasts
 * or advises; a value Benten computes says "Calculated from reported
 * figures"; nothing names a price.
 */
import type { StatementItem, StatementTab } from "@/features/statements/statement-data";
import type { PublicWebLocale } from "./locales";

export type StatementsCopy = {
  readonly heading: string;
  readonly lead: (count: string, first: string, last: string) => string;
  readonly fixture: string;
  readonly tabsLabel: string;
  readonly tabs: Record<StatementTab, string>;
  /** The unit and scale of each tab's values, under its table. */
  readonly units: Record<StatementTab, string>;
  readonly lines: Record<StatementItem, string>;
  readonly legend: { readonly label: string; readonly verified: string; readonly unverified: string; readonly calculated: string; readonly empty: string };
  readonly table: { readonly caption: (tab: string) => string; readonly item: string; readonly scroll: (tab: string) => string };
  readonly chart: { readonly summary: Record<StatementTab, string>; readonly loading: string; readonly error: string; readonly retry: string; readonly needsJavaScript: string };
  readonly readout: {
    readonly hint: string;
    readonly empty: (line: string, year: string) => string;
    readonly exact: string;
    readonly period: (start: string, end: string) => string;
    readonly asOf: (date: string) => string;
    /** A share count stated as of the annual report's cover date, which is not the fiscal year end. */
    readonly coverDate: (date: string) => string;
    /** Link text for an input whose filing is known only by its address. */
    readonly citedFiling: string;
    readonly filed: (form: string, date: string) => string;
    readonly concept: string;
    readonly accession: string;
    readonly notVerified: string;
    readonly calculated: string;
    readonly formula: string;
    readonly inputs: string;
    readonly op: Record<"divide" | "subtract", string>;
    readonly inputNotVerified: string;
    readonly inputCalculated: string;
  };
  /** The main lines the document prerenders for its newest years. */
  readonly summary: { readonly caption: (years: string) => string; readonly annualReport: string };
  /** The frame where every line loads from the statements file after hydration. */
  readonly full: {
    readonly needsJavaScript: (items: string, years: string) => string;
    readonly loading: (items: string, years: string) => string;
    readonly error: string;
    readonly retry: string;
    readonly loaded: string;
  };
  readonly evidence: {
    readonly description: (count: string, first: string) => string;
    readonly statusColumn: string;
    readonly verified: string;
  };
  readonly opensNewTab: string;
};

